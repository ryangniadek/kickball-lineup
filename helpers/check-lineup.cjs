const fs = require('fs');
const vm = require('vm');
const assert = require('assert');
const code = fs.readFileSync('outputs/kickball-lineup/app.js', 'utf8');
const element = { innerHTML: '', addEventListener() {}, classList: { add() {}, remove() {} } };
const localStorage = { getItem() { return null; }, setItem() {} };
const context = vm.createContext({
  document: { getElementById() { return element; }, querySelectorAll() { return []; } },
  window: { clearTimeout() {}, setTimeout() {}, confirm() { return true; }, print() {} },
  localStorage, structuredClone, crypto: require('crypto').webcrypto, console
});
vm.runInContext(code, context);
const check = expression => vm.runInContext(expression, context);
assert.equal(check('status().ready'), true, 'sample should be ready');
assert.equal(check('fieldReport("four").women'), 5);
assert.equal(check('fieldReport("rover").ready'), true);
check('state.order = ["sample-1","sample-2","sample-4","sample-0","sample-3","sample-5","sample-6","sample-7","sample-8","sample-9","sample-10","sample-11"]');
assert.equal(check('orderReport().ready'), false, 'three men at wrap should fail');
assert.ok(check('orderReport().issues.some(x => x.includes("Three men"))'));
check('state = sampleState(); state.players = Array.from({length:18}, (_,i) => ({id:String(i), name:String(i), gender:i<5?"W":"M", active:true})); state.order = state.players.map(p => p.id); state.rotations = {M:[],W:[]}');
assert.equal(check('usesSplitRotation()'), true, '13 men and 5 women should use separate rotations');
assert.equal(check('orderReport().ready'), false, 'missing men must be added to their rotation');
check('state.players.forEach(p => { if (!state.rotations[p.gender].includes(p.id)) state.rotations[p.gender].push(p.id); })');
assert.equal(check('orderReport().ready'), true, 'both complete rotations should be ready');
check('render()');
assert.ok(element.innerHTML.includes("Men's rotation") && element.innerHTML.includes("Women's rotation"), 'split UI should render both lanes');
assert.ok(element.innerHTML.includes('Next 30 kicks'), 'split UI should render preview');
const printKickPreview = check('printOrder()').match(/<div class="print-kick-grid">([\s\S]*?)<\/div>/)?.[1];
assert.ok(printKickPreview, 'split printout should show the actual kick sequence');
assert.equal((printKickPreview.match(/<span /g) || []).length, 30, 'printout should show the first 30 kicks');
assert.match(printKickPreview, /<b>1\.<\/b> 5<\/span><span class="woman"><b>2\.<\/b> 0<\/span><span class=""><b>3\.<\/b> 6<\/span>/, 'printed sequence should start man, woman, man');
assert.equal(check('generatedKicks(39).length'), 39);
assert.equal(check('generatedKicks(39).every((id,i) => player(id).gender === (i % 3 === 1 ? "W" : "M"))'), true, 'sequence must start MWM and keep two men between women');
assert.equal(check('generatedKicks(30).map(id => player(id).gender).slice(0,3).join("")'), 'MWM', 'first three kicks should be man, woman, man');
assert.equal(check('generatedKicks(30).map(id => player(id).gender).slice(-2).join("")'), 'WM', '30-kick preview should end woman, man');
assert.equal(check('generatedKicks(32).map(id => player(id).gender).slice(28).join("")'), 'WMMW', 'pattern should continue across the preview boundary');
assert.equal(check('generatedKicks(39).filter(id => player(id).gender === "M").slice(0,13).every((id,i) => id === state.rotations.M[i])'), true, 'men retain their own rotation');
assert.equal(check('generatedKicks(39).filter(id => player(id).gender === "W").slice(0,10).every((id,i) => id === state.rotations.W[i%5])'), true, 'women repeat independently');
check('state.fields = {four:{},rover:{}}');
const exportedLineup = check('JSON.stringify(lineupDocument())');
const parseLineupDocument = check('parseLineupDocument');
const importedLineup = parseLineupDocument(exportedLineup);
assert.equal(importedLineup.players.length, 18, 'export/import should retain every player');
assert.equal(importedLineup.rotations.M.length, 13, 'export/import should retain the mens rotation');
assert.equal(importedLineup.rotations.W.length, 5, 'export/import should retain the womens rotation');
assert.throws(() => parseLineupDocument('{broken'), /valid JSON/, 'malformed JSON should be rejected');
const duplicateRoster = JSON.parse(exportedLineup);
duplicateRoster.lineup.players[1].id = duplicateRoster.lineup.players[0].id;
assert.throws(() => parseLineupDocument(JSON.stringify(duplicateRoster)), /invalid player roster/, 'duplicate player IDs should be rejected');
check('state = sampleState(); state.fields.four.RF = undefined; state.fields.four.LCF = undefined');
assert.equal(check('fieldReport("four").ready'), false, 'eight fielders should fail');
check('state = sampleState(); state.fields.four.RF = undefined');
assert.equal(check('fieldReport("four").ready'), true, 'nine fielders with 4 women should pass');
check('state.fields.four.C = "sample-10"');
assert.equal(check('fieldReport("four").ready'), true, 'nine fielders with 3 women should pass');
check('state.fields.four["2B"] = "sample-11"');
assert.equal(check('fieldReport("four").ready'), false, 'nine fielders with 2 women should fail');
check('state = sampleState(); state.fieldRotations.four = [{id:"first",name:"1B",slots:["1B"],members:["sample-2","sample-10"]},{id:"center",name:"Center field",slots:["LCF","RCF"],members:["sample-7","sample-8","sample-11"]}]');
assert.equal(check('fieldForInning("four",1)["1B"]'), 'sample-2', 'first inning keeps the starter');
assert.equal(check('fieldForInning("four",2)["1B"]'), 'sample-10', 'first base rotates to bench player');
assert.equal(check('fieldForInning("four",3)["1B"]'), 'sample-2', 'first base cycles back');
assert.equal(check('fieldForInning("four",2).LCF'), 'sample-8', 'first center spot rotates');
assert.equal(check('fieldForInning("four",2).RCF'), 'sample-11', 'bench player enters second center spot');
assert.equal(check('fieldForInning("four",3).RCF'), 'sample-7', 'original center fielder reenters');
assert.equal(check('status().ready'), true, 'legal rotation groups keep lineup ready');
assert.equal(parseLineupDocument(check('JSON.stringify(lineupDocument())')).fieldRotations.four.length, 2, 'export/import should retain field rotation groups');
const printedDefense = check('printDefense("four")');
assert.match(printedDefense, /<strong>1B<\/strong><span>Sam<\/span><small>Rotates: Jamie<\/small>/, 'rotating bench player should print under first base');
assert.match(printedDefense, /<strong>LCF<\/strong><span>Morgan<\/span><small>Rotates: Alex<\/small>/, 'shared bench player should print under first center field spot');
assert.match(printedDefense, /<strong>RCF<\/strong><span>Casey<\/span><small>Rotates: Alex<\/small>/, 'shared bench player should print under second center field spot');
assert.ok(printedDefense.includes('Center field:'), 'rotation cycle should print below the field');
check('render()');
assert.ok(element.innerHTML.includes('print-sheet') && element.innerHTML.includes('Kicking order'), 'dedicated print sheet should render');
check('state.fields.four.RF = "sample-10"; state.fieldRotations.four[0].members = ["sample-2","sample-11"]; state.players.push({id:"sample-12",name:"Extra",gender:"M",active:true}); state.fieldRotations.four[1].members = ["sample-7","sample-8","sample-12"]');
assert.equal(check('status().four.ready'), false, 'later inning with only 3 women must fail');
assert.ok(check('status().four.issues.some(issue => issue.includes("Inning 2"))'), 'later inning issue should be visible');
console.log('Lineup rules checks passed.');
